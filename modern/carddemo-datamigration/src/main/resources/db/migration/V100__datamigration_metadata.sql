-- 1B data migration metadata (additive: no change to the V1 tables).

-- Physical layout of the last imported extract per dataset (relationalToVsam rebuilds
-- the original file byte-identical: record separator, last separator, right trim).
CREATE TABLE dm_dataset_layout (
    dataset          VARCHAR(16)  NOT NULL,
    source_format    VARCHAR(8)   NOT NULL,
    source_file      VARCHAR(64)  NOT NULL,
    layout           VARCHAR(64)  NOT NULL,
    record_count     BIGINT       NOT NULL,
    source_sha256    VARCHAR(64)  NOT NULL,
    job_execution_id BIGINT       NOT NULL,
    loaded_at        TIMESTAMP    NOT NULL,
    CONSTRAINT pk_dm_dataset_layout PRIMARY KEY (dataset)
);

-- Reconciliation metrics (count, checksums, column hashes) of every vsamToRelational run.
CREATE TABLE dm_reconciliation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_execution_id BIGINT       NOT NULL,
    dataset          VARCHAR(16)  NOT NULL,
    metric           VARCHAR(64)  NOT NULL,
    source_value     VARCHAR(128),
    target_value     VARCHAR(128),
    matched          BOOLEAN      NOT NULL,
    CONSTRAINT pk_dm_reconciliation PRIMARY KEY (id)
);
CREATE INDEX dm_reconciliation_exec ON dm_reconciliation (job_execution_id);

-- Reversible USRSEC -> {bcrypt} migration (job usrsecToBcrypt / usrsecRollback):
-- legacy SEC-USR-PWD kept until the cutover is confirmed (job usrsecPurgeBackup).
CREATE TABLE dm_usrsec_pwd_backup (
    sec_usr_id   VARCHAR(8)   NOT NULL,
    legacy_pwd   VARCHAR(8)   NOT NULL,
    migrated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT pk_dm_usrsec_pwd_backup PRIMARY KEY (sec_usr_id)
);
