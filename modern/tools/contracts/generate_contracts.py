def gen_entity(copybook, dto, entity, table, fields, pk, aix):
    pkg = "com.carddemo.domain." + ("user" if table == "app_user" else "entity")
    pkg = "com.carddemo.domain.entity"
    surrogate = pk is None
    pkf = [f for f in fields if pk and f["name"] in pk]
    composite = len(pkf) > 1
    imports = {"jakarta.persistence.Column", "jakarta.persistence.Entity", "jakarta.persistence.Table",
               "jakarta.persistence.Version", f"com.carddemo.contracts.record.{dto}"}
    if any(f["scale"] for f in fields):
        imports.add("java.math.BigDecimal")
    lines, accessors = [], []
    idtype = None
    if surrogate:
        imports |= {"jakarta.persistence.Id", "jakarta.persistence.GeneratedValue",
                    "jakarta.persistence.GenerationType"}
        lines.append('  @Id\n  @GeneratedValue(strategy = GenerationType.IDENTITY)\n'
                     '  @Column(name = "seq_no")\n  private Long seqNo;\n')
        accessors.append("  public Long getSeqNo() {\n    return seqNo;\n  }\n")
        idtype = "Long"
    elif composite:
        imports |= {"jakarta.persistence.EmbeddedId"}
        idtype = f"{entity}Id"
        lines.append(f"  @EmbeddedId\n  private {idtype} id;\n")
        accessors.append(f"  public {idtype} getId() {{\n    return id;\n  }}\n\n"
                         f"  public void setId({idtype} id) {{\n    this.id = id;\n  }}\n")
        gen_embedded_id(idtype, pkf)
    else:
        imports.add("jakarta.persistence.Id")
        idtype = java_type(pkf[0], True)
    for f in fields:
        if composite and f in pkf:
            continue
        n, t = camel(f["name"]), java_type(f, True)
        ann = "  @Id\n" if (not composite and f in pkf) else ""
        extra = f", precision = {f['digits']}, scale = {f['scale']}" if f["scale"] else (
            f", length = {100 if table == 'app_user' and f['name'] == 'SEC-USR-PWD' else f['length']}"
            if f["kind"] == "X" else "")
        lines.append(f'{ann}  @Column(name = "{column(f["name"])}", nullable = false{extra})\n  private {t} {n};\n')
        N = n[0].upper() + n[1:]
        accessors.append(f"  public {t} get{N}() {{\n    return {n};\n  }}\n\n"
                         f"  public void set{N}({t} {n}) {{\n    this.{n} = {n};\n  }}\n")
    lines.append('  @Version\n  @Column(name = "version", nullable = false)\n  private long version;\n')
    accessors.append("  public long getVersion() {\n    return version;\n  }\n")
    # mapping
    def getter(f):
        n = camel(f["name"])
        if composite and f in pkf:
            return f"id.{n}()"
        return n
    args = ",\n        ".join(getter(f) for f in fields)
    to_rec = f"  /** Maps this row back to the {copybook} record layout. */\n  public {dto} toRecord() {{\n    return new {dto}(\n        {args});\n  }}\n"
    sets = []
    if composite:
        sets.append(f"    e.id = new {idtype}(" + ", ".join(f"r.{camel(f['name'])}()" for f in pkf) + ");")
    for f in fields:
        if composite and f in pkf:
            continue
        sets.append(f"    e.{camel(f['name'])} = r.{camel(f['name'])}();")
    from_rec = (f"  /** Creates a row from a decoded {copybook} record. */\n  public static {entity} fromRecord({dto} r) {{\n"
                f"    {entity} e = new {entity}();\n" + "\n".join(sets) + "\n    return e;\n  }\n")
    idx = "".join(f'\n    @Index(name = "{n}", columnList = "{column(c)}"),' for n, c in aix.items())
    table_ann = (f'@Table(name = "{table}", indexes = {{{idx.rstrip(",")}\n}})' if aix else f'@Table(name = "{table}")')
    if aix:
        imports.add("jakarta.persistence.Index")
    body = (f"package {pkg};\n\n{HEADER}\n" + "".join(f"import {i};\n" for i in sorted(imports)) +
            f"\n/** Table {table} (VSAM {copybook}, plan §1.3). */\n@Entity\n{table_ann}\n"
            f"public class {entity} {{\n\n" + "\n".join(lines) + "\n" + "\n".join(accessors) + "\n" + to_rec + "\n" +
            from_rec + "}\n")
    write(DOMAIN / f"java/com/carddemo/domain/entity/{entity}.java", body)
    finders = "".join(
        f"\n  List<{entity}> findBy{camel(c, True)}({java_type(next(f for f in fields if f['name'] == c), True)} "
        f"{camel(c)});\n" for c in aix.values())
    repo = (f"package com.carddemo.domain.repository;\n\n{HEADER}\n"
            f"import com.carddemo.domain.entity.{entity};\n" +
            (f"import com.carddemo.domain.entity.{idtype};\n" if composite else "") +
            ("import java.util.List;\n" if aix else "") +
            "import org.springframework.data.jpa.repository.JpaRepository;\n\n"
            f"/** Repository for {table}; AIX lookups mirror the VSAM alternate indexes. */\n"
            f"public interface {entity}Repository extends JpaRepository<{entity}, {idtype}> {{{finders}}}\n")
    write(DOMAIN / f"java/com/carddemo/domain/repository/{entity}Repository.java", repo)


def gen_embedded_id(idtype, pkf):
    comps = ",\n    ".join(f'@Column(name = "{column(f["name"])}", nullable = false) {java_type(f, True)} {camel(f["name"])}'
                           for f in pkf)
    body = (f"package com.carddemo.domain.entity;\n\n{HEADER}\n"
            "import jakarta.persistence.Column;\nimport jakarta.persistence.Embeddable;\nimport java.io.Serializable;\n\n"
            f"/** Composite VSAM key. */\n@Embeddable\npublic record {idtype}(\n    {comps})\n    implements Serializable {{}}\n")
    write(DOMAIN / f"java/com/carddemo/domain/entity/{idtype}.java", body)


