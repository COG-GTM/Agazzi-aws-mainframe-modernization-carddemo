#!/usr/bin/env bash
# Rollback wrapper (runbook §R): PostgreSQL -> VSAM unload files -> IDCAMS REPRO on the mainframe.
# Wraps the Spring Batch job `relationalToVsam` (owner 1B b1-datalifecycle, see
# docs/cutover/rollback.md §"CLI contract") and makes the result safe to ship back:
#   1. checks the Java side is frozen (GET /actuator/maintenance closedFiles not empty) unless --no-freeze-check
#   2. runs `run-job.sh relationalToVsam datasets=.. format=.. output=..` (skipped with --from-dir)
#   3. verifies the export with Reconcile (counts + checksums, exported files vs DB) -> must be OK
#   4. writes SHA256SUMS and the IDCAMS DELETE/DEFINE/REPRO deck ROLLBACK.jcl for the reload
# usage: relational-to-vsam.sh --out DIR [--format ebcdic|ascii] [--datasets A,B] [--from-dir DIR]
#        [--db-url JDBC] [--base-url URL] [--no-freeze-check] [--hlq AWS.M2.CARDDEMO]
# env: CARDDEMO_DB_PASSWORD (reconcile), CARDDEMO_SMOKE_USER/PASSWORD (maintenance check)
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
out="" format="ebcdic" datasets="ACCTDATA,CARDDATA,CARDXREF,CUSTDATA,TCATBALF,DISCGRP,TRANTYPE,TRANCATG,TRANSACT,USRSEC"
from="" db_url="${CARDDEMO_DB_URL:-jdbc:postgresql://localhost:5432/carddemo}"
base_url="${CARDDEMO_BASE_URL:-http://localhost:8080}" freeze=1 hlq="AWS.M2.CARDDEMO"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --out) out="$2"; shift 2 ;; --format) format="$2"; shift 2 ;; --datasets) datasets="$2"; shift 2 ;;
    --from-dir) from="$2"; shift 2 ;; --db-url) db_url="$2"; shift 2 ;; --base-url) base_url="$2"; shift 2 ;;
    --hlq) hlq="$2"; shift 2 ;; --no-freeze-check) freeze=0; shift ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
[[ -n "$out" ]] || { echo "--out is required" >&2; exit 2; }
mkdir -p "$out"; out="$(cd "$out" && pwd)"
log() { echo "[relational-to-vsam] $*"; }

if [[ $freeze -eq 1 ]]; then
  auth=(); [[ -n "${CARDDEMO_SMOKE_USER:-}" ]] && auth=(-u "$CARDDEMO_SMOKE_USER:${CARDDEMO_SMOKE_PASSWORD:-}")
  # every CICS file of the CSD must be closed (or "*"), a partial freeze still allows writes
  open=$(curl -fsS "${auth[@]}" "$base_url/actuator/maintenance" 2>/dev/null | python3 -c '
import json, sys
closed = set(json.load(sys.stdin).get("closedFiles") or [])
need = ["ACCTDAT", "CARDAIX", "CARDDAT", "CCXREF", "CUSTDAT", "CXACAIX", "TRANSACT", "USRSEC"]
print(" ".join([] if "*" in closed else [f for f in need if f not in closed]))' 2>/dev/null) \
    || { log "cannot read $base_url/actuator/maintenance (use --no-freeze-check only if the ALB is already detached)"; exit 4; }
  [[ -n "$open" ]] && { log "Java files still open: $open — CLOSEFIL all of them first (runbook R.2)"; exit 4; }
fi

if [[ -z "$from" ]]; then
  # On ECS the task has its own filesystem: export to S3 and download to --out afterwards.
  target="$out"
  if [[ "${CARDDEMO_JOB_MODE:-local}" == ecs ]]; then
    target="s3://${CARDDEMO_GDG_BUCKET:?CARDDEMO_GDG_BUCKET (terraform output gdg_bucket)}/rollback/$(date -u +%Y%m%dT%H%M%SZ)/"
  fi
  log "running relationalToVsam datasets=$datasets format=$format output=$target"
  set +e; "$HERE/run-job.sh" relationalToVsam "datasets=$datasets" "format=$format" "output=$target"; rc=$?; set -e
  [[ $rc -eq 3 ]] && { log "job relationalToVsam not deployed yet (1B): BLOCKER, use the T-0 VSAM backup (runbook R.3b)"; exit 3; }
  [[ $rc -eq 0 ]] || { log "relationalToVsam failed rc=$rc"; exit $rc; }
  [[ "$target" == s3://* ]] && aws s3 cp --recursive --only-show-errors "$target" "$out/"
  src="$out"
else
  src="$(cd "$from" && pwd)"; log "verifying existing export in $src"
fi

log "reconciling export vs DB"
"$HERE/cutover.sh" reconcile --db-url "$db_url" --source-root "$src" --format "$format" \
  --datasets "$datasets" --manifest "$HERE/datasets.yaml" --out "$out/reconciliation"

python3 - "$HERE/datasets.yaml" "$src" "$out" "$format" "$datasets" "$hlq" "$HERE/../../docs/inventory/inventory.json" <<'PY'
import hashlib, json, sys, yaml
from pathlib import Path
manifest, src, out, fmt, names, hlq, inventory = sys.argv[1:]
ds = yaml.safe_load(open(manifest))["datasets"]
defs = {}
for j in json.load(open(inventory))["jcl"]:
    for d in j["defines"]:
        defs.setdefault(d["name"], d)
def kv(v):
    return v.replace(",", " ")
sums, deck = [], ["//ROLLBACK JOB 'CARDDEMO ROLLBACK',CLASS=A,MSGCLASS=0,NOTIFY=&SYSUID",
                  "//* GENERATED by modern/tools/cutover/rollback/relational-to-vsam.sh",
                  "//* Upload the files below as RECFM=F to <HLQ>.<DS>.ROLLBK, then submit.",
                  "//* Each KSDS is DELETEd and reDEFINEd (definitions from docs/inventory, as the",
                  "//* app/jcl *FILE jobs) so records deleted on the Java side do not survive the reload."]
for i, n in enumerate(names.split(",")):
    d = ds[n]
    p = Path(src) / d[fmt].split("#")[0]
    sums.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}")
    vsam = d["vsam"]
    if not vsam.endswith(".KSDS"):
        continue
    c = defs[vsam]
    # IDCAMS reads columns 1-72: one clause per line, " -" continuation (as app/jcl/*FILE.jcl).
    stmts = [f"  DELETE {vsam} -", "         CLUSTER PURGE", "  SET MAXCC = 0",
             "  DEFINE CLUSTER -", f"         (NAME({vsam}) -", f"         KEYS({kv(c['keys'])}) -",
             f"         RECORDSIZE({kv(c['recordsize'])}) -", "         INDEXED SHAREOPTIONS(2 3) -",
             "         ERASE CYLINDERS(1 5)) -", f"    DATA (NAME({vsam}.DATA)) -",
             f"    INDEX (NAME({vsam}.INDX))", "  REPRO INFILE(IN) -", f"         OUTDATASET({vsam})"]
    for aix in [x for x in defs.values() if x["type"] == "ALTERNATEINDEX" and x["relate"] == vsam]:
        stmts += ["  DEFINE ALTERNATEINDEX -", f"         (NAME({aix['name']}) -", f"         RELATE({vsam}) -",
                  f"         KEYS({kv(aix['keys'])}) -", f"         RECORDSIZE({kv(aix['recordsize'])}) -",
                  "         NONUNIQUEKEY UPGRADE CYLINDERS(1 5))"]
        for path in [x for x in defs.values() if x["type"] == "PATH" and x["relate"] == aix["name"]]:
            stmts += ["  DEFINE PATH -", f"         (NAME({path['name']}) -", f"         PATHENTRY({aix['name']}))"]
        stmts += ["  BLDINDEX -", f"         INDATASET({vsam}) -", f"         OUTDATASET({aix['name']})"]
    long = [l for l in stmts if len(l) > 71]
    if long:
        sys.exit(f"IDCAMS statement over 71 columns: {long[0]}")
    deck += [f"//S{i:02d}{n[:5]} EXEC PGM=IDCAMS", "//SYSPRINT DD SYSOUT=*",
             f"//IN       DD DISP=SHR,DSN={hlq}.{n}.ROLLBK", "//SYSIN    DD *", *stmts, "/*"]
Path(out, "SHA256SUMS").write_text("\n".join(sums) + "\n")
Path(out, "ROLLBACK.jcl").write_text("\n".join(deck) + "\n")
print(f"[relational-to-vsam] wrote {out}/SHA256SUMS ({len(sums)} files) and {out}/ROLLBACK.jcl")
PY
log "export verified: ship $out to the mainframe and submit ROLLBACK.jcl (runbook R.4)"
