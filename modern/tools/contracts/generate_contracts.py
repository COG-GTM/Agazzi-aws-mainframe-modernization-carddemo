def copybook_path(name):
    for ext in (".cpy", ".CPY"):
        p = APP / "cpy" / (name + ext)
        if p.exists():
            return p
    raise FileNotFoundError(name)


def parse_pic(pic):
    pic = pic.upper().rstrip(".")
    signed = pic.startswith("S")
    body = pic[1:] if signed else pic
    def expand(s):
        return re.sub(r"(.)\((\d+)\)", lambda m: m.group(1) * int(m.group(2)), s)
    e = expand(body)
    if set(e) <= {"X"}:
        return {"kind": "X", "length": len(e), "digits": 0, "scale": 0, "signed": False}
    if "V" in e:
        ip, fp = e.split("V")
    else:
        ip, fp = e, ""
    if not set(ip + fp) <= {"9"}:
        raise ValueError(pic)
    return {"kind": "9", "length": len(ip) + len(fp), "digits": len(ip) + len(fp), "scale": len(fp),
            "signed": signed}


def parse_copybook(name):
    """Flat copybook parser (DISPLAY fields, group levels flattened, FILLER kept)."""
    # CUSTREC.cpy has literal TABs in fixed-format columns: same normalisation as the golden harness.
    text = "\n".join(re.sub(r"^\t+ *", " " * 11, ln).replace("\t", " ")
                     for ln in copybook_path(name).read_text(encoding="latin-1").splitlines())
    code = " ".join(line[7:72] for line in text.splitlines() if not (len(line) > 6 and line[6] in "*/"))
    stmts = [x.strip() for x in re.split(r"\.(?=\s|$)", code) if x.strip()]
    fields, offset, fillers = [], 0, 0
    for s in stmts:
        m = re.match(r"(\d+)\s+(\S+)(.*)", s)
        if not m:
            continue
        level, fname, rest = m.groups()
        pm = re.search(r"PIC(?:TURE)?\s+(\S+)", rest)
        if level in ("88", "66") or not pm:
            continue
        info = parse_pic(pm.group(1))
        if fname == "FILLER":
            fillers += 1
            fname = "FILLER" if fillers == 1 else f"FILLER-{fillers}"
        info.update(name=fname, offset=offset)
        offset += info["length"]
        fields.append(info)
    return fields, offset


def camel(cobol, upper=False):
    for k, v in TYPOS.items():
        cobol = cobol.replace(k, v)
    parts = [p for p in cobol.lower().split("-") if p]
    s = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return s[0].upper() + s[1:] if upper else s


def column(cobol):
    for k, v in TYPOS.items():
        cobol = cobol.replace(k, v)
    return cobol.lower().replace("-", "_")


def java_type(f, boxed=False):
    if f["kind"] == "X":
        return "String"
    if f["scale"]:
        return "BigDecimal"
    if f["digits"] <= 9:
        return "Integer" if boxed else "int"
    return "Long" if boxed else "long"


def sql_type(f, table=None):
    if f["kind"] == "X":
        if table == "app_user" and f["name"] == "SEC-USR-PWD":
            return "VARCHAR(100)"  # plan §3.4 documented exception (password hash)
        return f"VARCHAR({f['length']})"
    if f["scale"]:
        return f"NUMERIC({f['digits']},{f['scale']})"
    return "INTEGER" if f["digits"] <= 9 else "BIGINT"


def pic_text(f):
    if f["kind"] == "X":
        return f"X({f['length']})"
    s = ("S" if f["signed"] else "") + f"9({f['digits'] - f['scale']})"
    return s + (f"V9({f['scale']})" if f["scale"] else "")


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


