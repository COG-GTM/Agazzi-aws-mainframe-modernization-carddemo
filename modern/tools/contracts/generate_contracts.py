def gen_sql(specs):
    out = ["-- GENERATED by modern/tools/contracts/generate_contracts.py - contracts-v1 baseline (plan §0.3, §1.3).",
           "-- Owner: Fase 0. Never edit: later changes go in the owner's Flyway range (plan §4.2).",
           "-- Logical FKs are documented with COMMENT (not enforced: batch reloads/IDCAMS REPRO order, plan §3.3).", ""]
    comments = []
    for copybook, dto, entity, table, length, data, pk, aix, fields in specs:
        cols = []
        if pk is None:
            cols.append("    seq_no BIGINT GENERATED BY DEFAULT AS IDENTITY")
        for f in fields:
            cols.append(f"    {column(f['name'])} {sql_type(f, table)} NOT NULL")
        cols.append("    version BIGINT NOT NULL DEFAULT 0")
        pkcols = ["seq_no"] if pk is None else [column(c) for c in pk]
        cols.append(f"    CONSTRAINT pk_{table} PRIMARY KEY ({', '.join(pkcols)})")
        out.append(f"-- {copybook} ({length} bytes)\nCREATE TABLE {table} (\n" + ",\n".join(cols) + "\n);")
        for n, c in aix.items():
            out.append(f"CREATE INDEX {n} ON {table} ({column(c)});")
        out.append("")
        for (t, c), target in LOGICAL_FK.items():
            if t == table:
                comments.append(f"COMMENT ON COLUMN {t}.{c} IS 'logical FK -> {target}';")
    user_fields = specs[-1][-1]
    for t, extra in (("usrsec_esds", "    rba BIGINT GENERATED BY DEFAULT AS IDENTITY"),
                     ("usrsec_rrds", "    rrn INTEGER NOT NULL")):
        cols = [extra] + [f"    {column(f['name'])} {sql_type(f)} NOT NULL" for f in user_fields]
        cols += ["    version BIGINT NOT NULL DEFAULT 0", f"    CONSTRAINT pk_{t} PRIMARY KEY ({extra.split()[0]})"]
        out.append(f"-- USRSEC {'ESDS (RBA = insertion order)' if 'esds' in t else 'RRDS (relative record number)'}"
                   f" demo, CSUSR01Y layout\nCREATE TABLE {t} (\n" + ",\n".join(cols) + "\n);\n")
    out += comments
    write(DOMAIN / "resources/db/migration/V1__baseline.sql", "\n".join(out) + "\n")


# ---------------------------------------------------------------- seed data (V2)
def zoned(raw, f):
    """Decodes zoned DISPLAY with trailing overpunch (plan §1.5)."""
    if f["kind"] == "X":
        return raw
    last = raw[-1]
    neg = False
    if f["signed"]:
        if last in "{ABCDEFGHI":
            last = str("{ABCDEFGHI".index(last))
        elif last in "}JKLMNOPQR":
            last, neg = str("}JKLMNOPQR".index(last)), True
    digits = (raw[:-1] + last).replace(" ", "0")
    if not digits.isdigit():
        raise ValueError(f"bad zoned {f['name']}: {raw!r}")
    v = int(digits)
    if f["scale"]:
        s = f"{v:0{f['digits']}d}"
        s = s[:-f["scale"]] + "." + s[-f["scale"]:]
        s = s.lstrip("0") or "0"
        s = ("0" + s) if s.startswith(".") else s
        return ("-" if neg else "") + s
    return ("-" if neg else "") + str(v)


def sql_literal(v, f):
    if f["kind"] == "X":
        return "'" + v.replace("'", "''") + "'"
    return v


def data_lines(name, length):
    raw = (APP / "data/ASCII" / name).read_bytes().decode("ascii")
    return [ln.rstrip("\r").ljust(length) for ln in raw.split("\n") if ln.rstrip("\r").strip()]


def user_rows():
    """Instream SYSUT1 of app/jcl/DUSRSECJ.jcl (10 users, CSUSR01Y layout)."""
    lines = (APP / "jcl/DUSRSECJ.jcl").read_text().splitlines()
    start = next(i for i, ln in enumerate(lines) if ln.startswith("//SYSUT1") and "DD *" in ln)
    rows = []
    for ln in lines[start + 1:]:
        if ln.startswith("/*") or ln.startswith("//"):
            break
        rows.append(ln.ljust(80)[:80])
    return rows


def gen_seed(specs):
    out = ["-- GENERATED by modern/tools/contracts/generate_contracts.py from app/data/ASCII/*.txt and",
           "-- app/jcl/DUSRSECJ.jcl. Immutable common seed (plan §11.2). Location classpath:db/seed",
           "-- (enabled by the local/test profiles; the aws profile loads real data through 1B).",
           "-- USRSEC passwords are kept as in the legacy file (plaintext, PARITY_EXCEPTIONS PE-001):",
           "-- the Fase 0 UserCredentialService accepts them; 1B migrates them to {bcrypt} (V100-V199).", ""]
    counts = {}
    for copybook, dto, entity, table, length, data, pk, aix, fields in specs:
        if data:
            rows = data_lines(data, length)
        elif table == "app_user":
            rows = user_rows()
        else:
            continue
        cols = ", ".join(column(f["name"]) for f in fields)
        vals = []
        for r in rows:
            vals.append("(" + ", ".join(sql_literal(zoned(r[f["offset"]:f["offset"] + f["length"]], f), f)
                                        for f in fields) + ")")
        out.append(f"-- {table}: {len(rows)} rows\nINSERT INTO {table} ({cols}) VALUES\n" + ",\n".join(vals) + ";\n")
        counts[table] = len(rows)
    write(DOMAIN / "resources/db/seed/V2__seed_sample_data.sql", "\n".join(out))
    return counts


