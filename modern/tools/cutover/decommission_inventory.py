#!/usr/bin/env python3
"""Generates docs/cutover/decommission-inventory.md: every mainframe artifact to switch off,
with its owning workstream (ownership.yaml) and the Java replacement that must be live first.

Sources: modern/ownership.yaml (legacy globs per workstream) + docs/inventory/inventory.json
(CSD, Control-M/CA-7, JCL, VSAM/GDG). `--check` fails if the committed file is stale.
"""
import argparse
import json
import sys
from pathlib import Path

import yaml

MODERN = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(MODERN / "tools/inventory"))
from check_ownership import matches  # noqa: E402  same glob semantics as the CI ownership check

REPO = MODERN.parent
OUT = MODERN / "docs/cutover/decommission-inventory.md"


def owners():
    ws = yaml.safe_load((MODERN / "ownership.yaml").read_text())["workstreams"]
    return [(w, g) for w, d in ws.items() for g in d.get("legacy") or []]


def owner_of(path, rules):
    hits = [w for w, g in rules if matches(path, g)]
    return hits[0] if hits else "(no source in app/)"


def render():
    rules = owners()
    inv = json.loads((MODERN / "docs/inventory/inventory.json").read_text())
    L = ["# Decommissioning inventory", "",
         "GENERATED by `modern/tools/cutover/decommission_inventory.py` from `modern/ownership.yaml` and",
         "`docs/inventory/inventory.json`. Do not edit by hand. Order and procedure: [decommissioning.md](decommissioning.md).",
         "", "Wave = shutdown order (decommissioning.md §3). `Owner` = workstream whose Java replacement must be",
         "signed off before the artifact is switched off.", ""]
    csd = inv["csd"]
    prog = {p["name"]: p["path"] for p in inv["programs"]}
    member = {j["job"]: j["path"] for j in inv["jcl"]}
    L += ["## 1. CICS CSD (`app/csd/CARDDEMO.CSD`) — wave W2", "", "| Type | Name | Target / DSN | Owner |", "|---|---|---|---|"]
    for t in inv["transactions"]:
        L.append(f"| TRANSACTION | {t['name']} | {t['program']} | {owner_of(prog.get(t['program'], ''), rules)} |")
    for kind in ("file", "mapset", "library", "db2entry", "db2tran"):
        for e in csd.get(kind) or []:
            L.append(f"| {kind.upper()} | {e['name']} | {e.get('dsname') or ''} | {owner_of('app/csd/CARDDEMO.CSD', rules)} |")
    sch = inv["scheduler"]
    L += ["", "## 2. Scheduler — wave W1", "", "### Control-M (`app/scheduler/*.ctm`)", "",
          "| Folder | Job | Member | Predecessors | Owner of member |", "|---|---|---|---|---|"]
    for f in sch["controlm"]:
        for j in f["jobs"]:
            L.append(f"| {f['folder']} | {j['job']} | {j['member']} | {', '.join(j['in']) or '-'} | {owner_of(member.get(j['member'], ''), rules)} |")
    L += ["", "### CA-7 (`app/scheduler/*.ca7`)", "", "| Job | Owner of member |", "|---|---|"]
    for j in sch["ca7_jobs"]:
        L.append(f"| {j} | {owner_of(member.get(j, ''), rules)} |")
    L += ["", "## 3. JCL and PROCs — wave W1 (scheduled) / W4 (utility, define)", "",
          "| Job | Member | Programs | Defines | Owner |", "|---|---|---|---|---|"]
    for j in sorted(inv["jcl"] + inv["procs"], key=lambda x: x["path"]):
        pgms = sorted({s["pgm"] for s in j["steps"] if s.get("pgm")})
        defs = ", ".join(d["name"] for d in j["defines"]) or "-"
        L.append(f"| {j['job']} | `{j['path']}` | {', '.join(pgms)} | {defs} | {owner_of(j['path'], rules)} |")
    L += ["", "## 4. Datasets — wave W3 (archive to S3 Glacier, then IDCAMS DELETE)", "",
          "| Dataset | Type | Org / LIMIT | Defined in | Archive key |", "|---|---|---|---|---|"]
    seen = set()
    for d in sorted(inv["datasets"], key=lambda x: x["name"]):
        if d["name"] in seen:
            continue
        seen.add(d["name"])
        org = d.get("org") or ""
        if d["type"] == "GENERATIONDATAGROUP":
            org = f"LIMIT {d.get('limit')}"
        key = f"s3://<archive-bucket>/mainframe/{'gdg' if d['type'] == 'GENERATIONDATAGROUP' else 'vsam'}/{d['name']}/"
        L.append(f"| {d['name']} | {d['type']} | {org} | {d.get('defined_in') or '-'} | `{key}` |")
    L += ["", "## 5. Load modules (programs) — wave W4", "", "| Program | Kind | Source | Owner |", "|---|---|---|---|"]
    for p in sorted(inv["programs"], key=lambda x: x["name"]):
        L.append(f"| {p['name']} | {p['kind']} | `{p['path']}` | {owner_of(p['path'], rules)} |")
    L += ["", "## Totals", "",
          f"- Transactions: {len(inv['transactions'])}; CSD files: {len(csd.get('file') or [])}; mapsets: {len(csd.get('mapset') or [])}",
          f"- Control-M jobs: {sum(len(f['jobs']) for f in sch['controlm'])}; CA-7 jobs: {len(sch['ca7_jobs'])}",
          f"- JCL: {len(inv['jcl'])}; PROCs: {len(inv['procs'])}; datasets: {len(seen)} "
          f"(GDG bases: {sum(1 for d in inv['datasets'] if d['type'] == 'GENERATIONDATAGROUP' and d['name'] in seen)})",
          f"- Programs: {len(inv['programs'])}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run tools/cutover/decommission_inventory.py", file=sys.stderr)
            return 1
        print("decommission inventory up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
