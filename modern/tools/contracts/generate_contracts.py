def gen_record(copybook, dto, length):
    fields, total = parse_copybook(copybook)
    assert total == length, (copybook, total, length)
    imports = "import java.math.BigDecimal;\n" if any(f["scale"] for f in fields) else ""
    comps = []
    for f in fields:
        comps.append(f'    @CobolField(name = "{f["name"]}", pic = "{pic_text(f)}", offset = {f["offset"]}, '
                     f'length = {f["length"]})\n        {java_type(f)} {camel(f["name"])}')
    body = (f"package com.carddemo.contracts.record;\n\n{HEADER}\n"
            f"import com.carddemo.contracts.copybook.CobolField;\n"
            f"import com.carddemo.contracts.copybook.CobolRecord;\n{imports}\n"
            f"/** Copybook {copybook} ({length} bytes). PIC X fields keep their padding (plan §3.4). */\n"
            f'@CobolRecord(copybook = "{copybook}", length = {length})\n'
            f"public record {dto}(\n" + ",\n".join(comps) + ") {}\n")
    write(CONTRACTS / f"java/com/carddemo/contracts/record/{dto}.java", body)
    return fields


